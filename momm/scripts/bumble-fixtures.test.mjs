import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {BumbleFixtureLedger} from './bumble-fixtures.mjs';
delete process.env.MOMM_EVIDENCE_HOME;
const parent=fs.mkdtempSync(path.join(os.tmpdir(),'momm-fixture-ledger-test-'));
const root=path.join(parent,'private');
const H=value=>crypto.createHash('sha256').update(value).digest('hex');
const frame=[{id:'d',kind:'defect',sha256:H('d'),split:'qualification'},{id:'c',kind:'control',sha256:H('c'),split:'qualification'},{id:'held',kind:'control',sha256:H('held'),split:'holdout'}];
const options={root,frame,scope_binding:H('operator-group'),budget:{max_total_attempts:3,max_transmissions:2,deadline:10000}};
try{
  const ledger=new BumbleFixtureLedger(options);
  const a=ledger.reserve('d',{purpose:'qualification',binding:H('worker-role'),now:1});
  assert.equal(a.fresh_evidence,true);
  assert.throws(()=>ledger.reserve('d',{purpose:'qualification',binding:H('other-profile'),now:2}),/reserved/);
  ledger.markTransmissionPossible(a.attempt_id,2);
  ledger.finish(a.attempt_id,{outcome:'outcome_unknown',now:3});
  const restart=new BumbleFixtureLedger(options);
  assert.equal(restart.summary().total_attempts,1);
  assert(restart.summary().burned_fixture_ids.includes('d'));
  assert.throws(()=>restart.reserve('d',{purpose:'qualification',binding:H('same'),now:4}),/burned/);
  assert.throws(()=>restart.reserve('held',{purpose:'diagnostic',binding:H('same'),now:4}),/held/);
  const b=restart.reserve('c',{purpose:'qualification',binding:H('worker-role'),now:4});
  restart.finish(b.attempt_id,{outcome:'known_not_sent',now:5});
  assert(!restart.summary().burned_fixture_ids.includes('c'));
  const c=restart.reserve('c',{purpose:'qualification',binding:H('worker-role'),now:6});
  assert.equal(c.fresh_evidence,true);
  restart.markTransmissionPossible(c.attempt_id,7);
  assert.throws(()=>restart.finish(c.attempt_id,{outcome:'known_not_sent',now:8}),/transmission/);
  restart.finish(c.attempt_id,{outcome:'success',now:8});
  assert.throws(()=>restart.finish(c.attempt_id,{outcome:'success',now:9}),/terminal/);
  assert.throws(()=>restart.reserve('held',{purpose:'holdout',binding:H('role'),now:9}),/budget/);
  assert.equal(restart.summary().total_attempts,3);
  assert.equal(restart.summary().transmission_possible_count,2);
  assert.equal(restart.summary().quorum_votes,0);
  assert(restart.summary().unresolved_attempt_ids.includes(a.attempt_id));
  assert.throws(()=>new BumbleFixtureLedger({...options,scope_binding:H('different')}),/binding/);
  assert.throws(()=>new BumbleFixtureLedger({...options,budget:{...options.budget,max_total_attempts:4}}),/binding/);
  assert.throws(()=>restart._locked(()=>{fs.unlinkSync(path.join(root,'writer.lock'));fs.writeFileSync(path.join(root,'writer.lock'),'foreign lock');}),/reconciliation/);
  assert.equal(fs.readFileSync(path.join(root,'writer.lock'),'utf8'),'foreign lock');
  fs.unlinkSync(path.join(root,'writer.lock'));
  fs.writeFileSync(path.join(root,'writer.lock'),'retained lock');
  assert.throws(()=>restart.reserve('held',{purpose:'holdout',binding:H('role'),now:9}),/busy/);
  fs.unlinkSync(path.join(root,'writer.lock'));
  const journal=path.join(root,'fixtures.jsonl');const original=fs.readFileSync(journal);
  fs.appendFileSync(journal,'{"incomplete":');
  assert.throws(()=>restart.summary(),/journal/);
  fs.writeFileSync(journal,original);
  assert.equal(restart.summary().total_attempts,3);
  const lateRoot=path.join(parent,'late-private'),late=new BumbleFixtureLedger({...options,root:lateRoot,budget:{max_total_attempts:2,max_transmissions:2,deadline:10}});
  const lateAttempt=late.reserve('d',{purpose:'qualification',binding:H('role'),now:1});
  late.markTransmissionPossible(lateAttempt.attempt_id,2);
  assert.throws(()=>late.finish(lateAttempt.attempt_id,{outcome:'success',now:11}),/Late/);
  late.finish(lateAttempt.attempt_id,{outcome:'stale',now:11});
  assert(late.summary().unresolved_attempt_ids.includes(lateAttempt.attempt_id));
  assert.throws(()=>late.reserve('c',{purpose:'qualification',binding:H('role'),now:12}),/budget/);
  console.log(JSON.stringify({passed:true,network_calls:0,scope:'private filesystem fixture burns and attempt bounds across restart; not remote execution or lease recovery'}));
}finally{
  assert(path.resolve(parent).startsWith(path.resolve(os.tmpdir())+path.sep+'momm-fixture-ledger-test-'));
  fs.rmSync(parent,{recursive:true,force:true});
}
